export const currencySymbols: Record<SupportedCurrency, string> = {
  USD: '$',
  EUR: '€',
  GBP: '£',
  JPY: '¥',
  UZS: "so'm",
  AED: 'AED',
  RUB: '₽',
  CNY: '¥',
  CAD: 'CA$',
  AUD: 'AU$',
};

